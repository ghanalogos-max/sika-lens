/**
 * SHA-256 and PBKDF2-HMAC-SHA256 (RFC 8018) in plain TypeScript.
 * Used to turn a backup passphrase into an AES-256 key without another package.
 */

function rotr(x: number, n: number): number {
  return ((x >>> n) | (x << (32 - n))) >>> 0;
}

